// Regenerates src/audio/soundfont-catalog-data.js from the .sf2 files, so the game can list every
// instrument without downloading it first. Run after adding or replacing a SoundFont:
//   node tools/sf2-catalog.mjs [dir]        (default dir: soundfonts/GeneralUser-GS)
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseSf2 } from '../src/lib/sf2.js';

const dir = process.argv[2] ?? 'soundfonts/GeneralUser-GS';
const files = readdirSync(dir).filter(f => f.endsWith('.sf2')).sort();
const catalog = files.map(file =>
{
    const path = join(dir, file);
    const b = readFileSync(path);
    const sf = parseSf2(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength));
    const presets = sf.presets
        .filter(p => p.regions.length && !/^-+$/.test(p.name))      // skip empty and placeholder ("----") presets
        .map(p => ({ bank: p.bank, program: p.program, name: p.name }));
    console.log(`${file}: ${presets.length} presets`);
    return { url: path, bytes: statSync(path).size, presets };
});

const lines = catalog.map(({ url, bytes, presets }) =>
    `    { url: ${JSON.stringify(url)}, bytes: ${bytes}, presets: [\n` +
    presets.map(p => `        { bank: ${p.bank}, program: ${p.program}, name: ${JSON.stringify(p.name)} },\n`).join('') +
    '    ] },\n');
writeFileSync('src/audio/soundfont-catalog-data.js',
    '// Generated by tools/sf2-catalog.mjs. Do not edit; rerun the tool.\n' +
    '// Every playable preset and the .sf2 file (url relative to index.html) that holds it.\n' +
    `export const SOUNDFONTS = [\n${lines.join('')}];\n`);
