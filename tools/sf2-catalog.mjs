// Regenerates src/audio/soundfont-catalog-data.js from the .sf2 files of every library in
// src/audio/soundfont-libraries-data.js, so the game can list every instrument without downloading them first.
// Run after adding or replacing a SoundFont:
//   node tools/sf2-catalog.mjs
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseSf2 } from '../src/lib/sf2.js';
import { LIBRARY_SOURCES } from '../src/audio/soundfont-libraries-data.js';

const libraries = LIBRARY_SOURCES.map(({ id, name, dir, license }) =>
{
    const files = readdirSync(dir).filter(f => /\.sf2$/i.test(f)).sort().map(file =>
    {
        const path = join(dir, file);
        const b = readFileSync(path);
        const sf = parseSf2(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength));
        const presets = sf.presets
            .filter(p => p.regions.length && !/^-+$/.test(p.name))      // skip empty and placeholder ("----") presets
            .map(p => ({ bank: p.bank, program: p.program, name: p.name.trim() }))
            .sort((a, b)=> a.bank - b.bank || a.program - b.program);
        console.log(`${path}: ${presets.length} presets`);
        return { url: path, bytes: statSync(path).size, presets };
    });
    if (!files.length) throw new Error(`no .sf2 files in ${dir}`);
    return { id, name, license, files };
});

const fileLines = ({ url, bytes, presets }) =>
    `        { url: ${JSON.stringify(url)}, bytes: ${bytes}, presets: [\n` +
    presets.map(p => `            { bank: ${p.bank}, program: ${p.program}, name: ${JSON.stringify(p.name)} },\n`).join('') +
    '        ] },\n';
const lines = libraries.map(({ id, name, license, files }) =>
    `    { id: ${JSON.stringify(id)}, name: ${JSON.stringify(name)}, license: ${JSON.stringify(license)}, files: [\n` +
    files.map(fileLines).join('') +
    '    ] },\n');
writeFileSync('src/audio/soundfont-catalog-data.js',
    '// Generated by tools/sf2-catalog.mjs. Do not edit; rerun the tool.\n' +
    '// Every library, its .sf2 files (urls relative to index.html) and every playable preset in each.\n' +
    `export const LIBRARIES = [\n${lines.join('')}];\n`);
